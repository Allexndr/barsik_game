/**
 * Эмодзи тоже уходят номером, а не символом.
 *
 * Символ в канале — это опять произвольная строка: набором эмодзи можно
 * сложить и оскорбление, и «позвони мне» с цифрами. Номер из закрытого списка
 * такого не позволяет.
 */
