const BY_ID = new Map<number, ChatPhrase>(CHAT_PHRASES.map((p) => [p.id, p]));
const EMOJI_BY_ID = new Map<number, string>(CHAT_EMOJI.map((e) => [e.id, e.glyph]));

/**
 * Что показать за пришедший номер.
 *
 * Незнакомый номер — не ошибка и не повод для заглушки вроде «???»: так на
 * экран ребёнка попадёт хоть что-то, чего в каталоге нет. Возвращаем null, и
 * реплика просто не появляется.
 */
export function renderChat(id: number, lang: 'ru' | 'kk'): string | null {
  const phrase = BY_ID.get(id);
  if (phrase) return lang === 'kk' ? phrase.kk : phrase.ru;
  return EMOJI_BY_ID.get(id) ?? null;
}

export function isChatId(id: unknown): id is number {
  return typeof id === 'number' && (BY_ID.has(id) || EMOJI_BY_ID.has(id));
}

