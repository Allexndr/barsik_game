/**
 * Чат хаба.
 *
 * Свободного ввода здесь нет и не должно быть. Игроки — дети 5–12 лет, и
 * открытый текст между детьми это ровно та дыра, на которой обожглись все
 * детские онлайн-миры: через неё идут травля, выманивание личных данных и
 * взрослые, притворяющиеся детьми. Шарарам именно поэтому перешёл на готовые
 * фразы.
 *
 * Ключевое здесь не фильтр, а протокол: по сети уходит **номер фразы**, а не
 * текст. Даже переписанный клиент не может отправить ребёнку произвольную
 * строку — принимающая сторона рисует фразу из своего каталога и молча
 * выбрасывает незнакомый номер. Фильтровать нечего, потому что текста в канале
 * нет вовсе.
 *
 * Побочная выгода: фраза приходит номером, а показывается на языке
 * получателя. Русскоязычный и казахоязычный ребёнок понимают друг друга без
 * перевода.
 */

export type ChatGroup = 'hello' | 'play' | 'kind' | 'feel' | 'help';

export interface ChatPhrase {
  /** Номер, который уходит в сеть. Менять у существующих нельзя. */
  id: number;
  group: ChatGroup;
  ru: string;
  kk: string;
}

